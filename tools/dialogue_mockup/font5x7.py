GLYPH_CHARS = (
    "ABCDEFGHIJKLMNOPQRSTUVWXYZ"
    "0123456789"
    " -.:/%+()?"
)


def glyph_index(char: str) -> int:
    upper = char.upper()
    if upper in GLYPH_CHARS:
        return GLYPH_CHARS.index(upper)
    return GLYPH_CHARS.index(" ")


def measure_text_width(text: str) -> int:
    return len(text) * 6


def draw_text(
    pixels: list[list[tuple[int, int, int, int]]],
    x: int,
    y: int,
    text: str,
    color: tuple[int, int, int, int],
) -> None:
    cursor_x = x
    height = len(pixels)
    width = len(pixels[0]) if pixels else 0
    for char in text:
        glyph = FONT5X7[glyph_index(char)]
        for row in range(7):
            py = y + row
            if py < 0 or py >= height:
                continue
            for col in range(5):
                if glyph[row] & (1 << (4 - col)):
                    px = cursor_x + col
                    if 0 <= px < width:
                        pixels[py][px] = color
        cursor_x += 6
